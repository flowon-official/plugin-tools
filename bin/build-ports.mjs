#!/usr/bin/env node
// Builds a plugin's packages for OpenAI Codex and GitHub Copilot from its Claude Code source, so the three never
// drift: the skills, hooks and agents are written once (for Claude Code), and this script writes the rest.
//
//   .codex-plugin/plugin.json     Codex's manifest: the skills, the generated command skills, the Codex hooks, interface
//   .github/plugin/plugin.json    Copilot's manifest (read before .claude-plugin/plugin.json): skills, agents, hooks
//   ports/skills/<command>/       each command as a skill only the user invokes (neither client loads Claude commands
//                                 from a plugin); a hand-written ports/skills/ folder that isn't a command (setup) is kept
//   ports/codex/hooks.json        the hooks for Codex: its tool names, and --client codex
//   ports/codex/agents/*.toml     the agents as Codex custom agents (a plugin can't ship them: a setup skill copies them)
//   ports/copilot/hooks.json      the hooks for Copilot: version 1, its tool names, and --client copilot
//   ports/copilot/agents/*.agent.md  the agents for Copilot, with its tool names
//
// What the Claude manifest doesn't say comes from the plugin's ports/config.json (all optional):
//   short          Codex's short description, at most 30 characters (default: the plugin's name)
//   category       Codex's category (default: Developer Tools)
//   codexAgentPrefix  the prefix of the agents' Codex names (default: the plugin's name), see codexAgent
//   servers        { "<MCP server in .mcp.json>": { "title": "Logic Foundry" } }: how an agent's tool list names it
//   rewrites       [{ "pattern", "flags", "replacement" }]: plugin-specific text changes for the other clients;
//                  {plugin} in a replacement is the plugin's name
//
// node build-ports.mjs [<plugin folder>]          writes them (default: the current folder)
// node build-ports.mjs --check [<plugin folder>]  fails when a written file isn't what the source gives (run in CI)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const args = process.argv.slice(2);
const check = args.includes('--check');
const pluginDir = resolve(args.find(a => !a.startsWith('--')) ?? '.');
const stale = [];

// Files this script wrote carry this marker; older ones name the script by its former path.
const MARKER = 'Generated by plugin-tools build-ports';
const MARKERS = [MARKER, 'Generated by scripts/build-ports.mjs'];

const readJson = file => JSON.parse(readFileSync(file, 'utf8'));
const json = value => JSON.stringify(value, null, 2) + '\n';
const quote = text => JSON.stringify(text);
const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// A pattern for the text in any case, without regular-expression flags (which a client's matcher may not take):
// foundry → [Ff][Oo][Uu][Nn][Dd][Rr][Yy].
const anyCase = text => [...text].map(c => c.toLowerCase() === c.toUpperCase() ? escape(c) : `[${c.toUpperCase()}${c.toLowerCase()}]`).join('');

function write(file, text) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;

  if (current === text) {
    return;
  }

  if (check) {
    stale.push(relative(pluginDir, file));
    return;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

function remove(path) {
  if (check) {
    stale.push(relative(pluginDir, path));
  } else {
    rmSync(path, { recursive: true, force: true });
  }
}

// A Markdown file's frontmatter (simple key: value lines) and body.
function parse(text) {
  const match = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);

  if (!match) {
    return { meta: {}, body: text };
  }

  const meta = {};

  for (const line of match[1].split('\n')) {
    const field = line.match(/^([\w-]+):\s*(.*)$/);
    if (field) {
      meta[field[1]] = field[2].trim().replace(/^"(.*)"$/, '$1');
    }
  }

  return { meta, body: match[2] };
}

const claudeManifest = join(pluginDir, '.claude-plugin', 'plugin.json');

if (!existsSync(claudeManifest)) {
  console.error(`${pluginDir} has no .claude-plugin/plugin.json.`);
  process.exit(2);
}

const manifest = readJson(claudeManifest);
const plugin = manifest.name;
const configFile = join(pluginDir, 'ports', 'config.json');
const config = existsSync(configFile) ? readJson(configFile) : {};
const mcpFile = join(pluginDir, '.mcp.json');
const servers = existsSync(mcpFile) ? Object.keys(readJson(mcpFile).mcpServers ?? {}) : [];

// Claude Code names a plugin's MCP tools mcp__plugin_<plugin>_<server>__<tool>; the other clients configure the server
// themselves under the same name, and Copilot's agents name its tools <server>/<tool>.
const claudeTools = server => new RegExp(escape(`mcp__plugin_${plugin}_${server}__`), 'g');

// An agent's name in Codex, which takes only lowercase letters, digits and underscores, with a prefix so it doesn't
// replace one of Codex's own agents (explorer): reviewer → logic_fabric_reviewer.
const codexAgent = name => `${config.codexAgentPrefix ?? plugin}_${name}`.replace(/-/g, '_');

// The text of a command or agent as another client reads it.
function portText(text) {
  let result = text
    .replace(/\$ARGUMENTS/g, '(the text the user gave after the skill\'s name)')
    .replace(/\(`AskUserQuestion`\)/g, '(one question to the user)')
    .replace(/`AskUserQuestion`/g, 'one question to the user');

  for (const rewrite of config.rewrites ?? []) {
    result = result.replace(new RegExp(rewrite.pattern, rewrite.flags ?? ''), rewrite.replacement.replaceAll('{plugin}', plugin));
  }

  for (const server of servers) {
    result = result.replace(claudeTools(server), `${server}/`);
  }

  // Codex's name for the agent, next to Copilot's (the same as Claude Code's).
  return result.replace(new RegExp('`' + escape(plugin) + ':([a-z-]+)` agent', 'g'), (all, agent) => `${all} (\`${codexAgent(agent)}\` in Codex)`);
}

// A hook command that finds the plugin's folder whatever the client gives: the PLUGIN_ROOT (or COPILOT_PLUGIN_ROOT,
// CLAUDE_PLUGIN_ROOT) variable, or the --root argument when the client substitutes ${PLUGIN_ROOT} in the command
// instead. node -e reads the same under bash, PowerShell and cmd.
function launcher(script, client) {
  const code = "const a=process.argv,i=a.indexOf('--root'),e=process.env,r=e.PLUGIN_ROOT||e.COPILOT_PLUGIN_ROOT||e.CLAUDE_PLUGIN_ROOT||(i>0&&!String(a[i+1]).includes('\\x24')?a[i+1]:'');"
    + `import(require('url').pathToFileURL(require('path').join(r,'hooks','${script}')).href)`;

  return `node -e "${code}" -- --client ${client} --root "\${PLUGIN_ROOT}"`;
}

const script = command => command.match(/hooks\/([\w-]+\.mjs)/)?.[1];

// Claude Code's hooks for another client: its event and tool names, and the launcher.
function portHooks(claude, client) {
  const matchers = client === 'codex'
    ? { 'Write|Edit|MultiEdit': 'apply_patch|Edit|Write', 'Bash|PowerShell': 'Bash' }
    : { 'Write|Edit|MultiEdit': 'Write|Edit', 'Bash|PowerShell': 'Bash' };
  const hooks = {};

  for (const [event, groups] of Object.entries(claude.hooks)) {
    hooks[event] = groups.map(group => {
      let matcher = group.matcher;

      if (matcher) {
        if (matchers[matcher]) {
          matcher = matchers[matcher];
        } else {
          // Codex names a configured server's tools mcp__<server>__<tool>. It also reaches a server the user added to
          // ChatGPT as an app, as mcp__codex_apps__<app>__<tool> (<app> is the app's name, such as
          // logic_fabric_foundry_1), so its matcher also takes those of an app with the server's name in its own.
          // Copilot names them <server>-<tool> (undocumented, seen live) after the name the user gave the server, such
          // as Logic-Fabric-Foundry in the Copilot app, so its matcher takes any name with the server's in it, in any
          // case. The hooks check the name again.
          for (const server of servers) {
            if (client !== 'codex') {
              matcher = matcher.replace(claudeTools(server), `.*${anyCase(server)}.*`);
            } else if (claudeTools(server).test(matcher)) {
              matcher = `${matcher.replace(claudeTools(server), `mcp__${server}__`)}|${matcher.replace(claudeTools(server), `mcp__codex_apps__.*${anyCase(server)}.*_`)}`;
            }
          }
        }
      }

      const entries = group.hooks.map(hook => client === 'codex'
        ? { type: 'command', command: launcher(script(hook.command), client), timeout: hook.timeout }
        : { type: 'command', command: launcher(script(hook.command), client), timeoutSec: hook.timeout });

      return matcher ? { matcher, hooks: entries } : { hooks: entries };
    });
  }

  // Copilot drops a prompt hook's added context in some versions; the session's start carries it too.
  if (client === 'copilot' && hooks.UserPromptSubmit) {
    hooks.SessionStart = hooks.UserPromptSubmit;
  }

  return client === 'copilot' ? { version: 1, hooks } : { description: claude.description, hooks };
}

// Copilot's names for Claude Code's tools in an agent's tools list (unknown names are ignored, so both the CLI's and
// VS Code's names are given).
const COPILOT_TOOLS = {
  Read: ['view', 'read'],
  Grep: ['rg', 'search'],
  Glob: ['glob'],
  Write: ['create', 'edit', 'apply_patch'],
  Edit: ['edit', 'apply_patch'],
  Bash: ['bash', 'powershell'],
};

function portAgents() {
  const folder = join(pluginDir, 'agents');

  if (!existsSync(folder)) {
    return null;
  }

  const written = [];

  for (const file of readdirSync(folder).filter(f => f.endsWith('.md'))) {
    const { meta, body } = parse(readFileSync(join(folder, file), 'utf8'));
    const tools = (meta.tools || '').split(',').map(t => t.trim()).filter(Boolean);
    const serverOf = tool => servers.find(server => tool.match(claudeTools(server)));
    const copilot = [...new Set(tools.flatMap(t => COPILOT_TOOLS[t] ?? [serverOf(t) ? t.replace(claudeTools(serverOf(t)), `${serverOf(t)}/`) : t]))];
    const text = portText(body).trim();
    const copilotFile = join(pluginDir, 'ports', 'copilot', 'agents', `${meta.name}.agent.md`);
    const codexFile = join(pluginDir, 'ports', 'codex', 'agents', `${codexAgent(meta.name)}.toml`);

    written.push(copilotFile, codexFile);
    write(copilotFile,
      `---\nname: ${meta.name}\ndescription: ${quote(meta.description)}\ntools: ${JSON.stringify(copilot)}\n---\n\n${text}\n`);

    // Codex has no tool list for an agent, so its instructions name the server tools it may use.
    const allowed = servers.map(server => {
      const names = tools.filter(t => t.match(claudeTools(server))).map(t => t.replace(claudeTools(server), ''));
      return names.length ? `Use only these ${config.servers?.[server]?.title ?? server} tools: ${names.join(', ')}.` : null;
    }).filter(Boolean);
    const readOnly = allowed.length && !tools.includes('Write') && !tools.includes('Edit') ? ' Don\'t change any file.' : '';
    const preamble = allowed.length ? `${allowed.join(' ')}${readOnly}\n\n` : '';

    if (text.includes("'''")) {
      throw new Error(`${file} contains ''', which a TOML literal string can't hold.`);
    }

    write(codexFile,
      `# ${MARKER} from agents/${file}.\nname = ${quote(codexAgent(meta.name))}\ndescription = ${quote(meta.description)}\ndeveloper_instructions = '''\n${preamble}${text}\n'''\n`);
  }

  return written;
}

function portCommands() {
  const folder = join(pluginDir, 'commands');

  if (!existsSync(folder)) {
    return [];
  }

  const names = [];

  for (const file of readdirSync(folder).filter(f => f.endsWith('.md'))) {
    const name = file.replace(/\.md$/, '');
    const { meta, body } = parse(readFileSync(join(folder, file), 'utf8'));
    // A command is the user's to run, unless its front matter says `disable-model-invocation: false`: then the agent
    // may run it too, as Claude Code lets it, for example when the user picks it as the next step.
    const agentRuns = String(meta['disable-model-invocation']).toLowerCase() === 'false';
    const lines = [
      '---',
      `name: ${name}`,
      `description: ${quote(meta.description)}`,
      ...(meta['argument-hint'] ? [`argument-hint: ${quote(meta['argument-hint'])}`] : []),
      'user-invocable: true',
      `disable-model-invocation: ${!agentRuns}`,
      '---',
      '',
      `<!-- ${MARKER} from commands/${file}. -->`,
      '',
    ];

    write(join(pluginDir, 'ports', 'skills', name, 'SKILL.md'), lines.join('\n') + portText(body).trimStart());
    write(join(pluginDir, 'ports', 'skills', name, 'agents', 'openai.yaml'),
      `# ${MARKER}: ${agentRuns ? 'the user runs this skill, and so may Codex when the user asks for it.' : 'Codex runs this skill only when the user asks for it.'}\ninterface:\n  display_name: ${quote(`${plugin}: ${name}`)}\npolicy:\n  allow_implicit_invocation: ${agentRuns}\n`);
    names.push(name);
  }

  return names;
}

const commands = portCommands();
const agents = portAgents();
const portSkills = existsSync(join(pluginDir, 'ports', 'skills')) || commands.length > 0;
const claudeHooks = join(pluginDir, 'hooks', 'hooks.json');
const hooks = existsSync(claudeHooks) ? readJson(claudeHooks) : null;

if (hooks) {
  write(join(pluginDir, 'ports', 'codex', 'hooks.json'), json(portHooks(hooks, 'codex')));
  write(join(pluginDir, 'ports', 'copilot', 'hooks.json'), json(portHooks(hooks, 'copilot')));
}

const skills = ['./skills/', ...(portSkills ? ['./ports/skills/'] : [])];
const common = {
  name: manifest.name,
  version: manifest.version,
  description: manifest.description.replace(/ from Claude Code/g, ''),
  author: manifest.author,
  homepage: manifest.homepage,
  repository: manifest.repository,
  license: manifest.license,
  keywords: manifest.keywords,
};
const setup = existsSync(join(pluginDir, 'ports', 'skills', 'setup', 'SKILL.md'));
const icon = existsSync(join(pluginDir, '.claude-plugin', 'icon.png')) ? './.claude-plugin/icon.png' : undefined;

write(join(pluginDir, '.codex-plugin', 'plugin.json'), json({
  ...common,
  skills,
  // Codex turns a plugin's Claude commands into skills of its own on install, Claude text included, and skips those
  // that take arguments; the command skills in ports/skills/ replace them.
  ...(commands.length ? { commands: [] } : {}),
  ...(hooks ? { hooks: './ports/codex/hooks.json' } : {}),
  // Codex reads the plugin's .mcp.json, whose settings are Claude Code's (such as ${user_config.<name>} in an address),
  // and fails on them in every session; a setup skill configures the servers in Codex instead.
  ...(servers.length ? { mcpServers: {} } : {}),
  ...(setup ? { extensions: { 'com.openai': { onboardingSkill: './ports/skills/setup/SKILL.md' } } } : {}),
  interface: {
    displayName: manifest.displayName ?? manifest.name,
    shortDescription: config.short ?? plugin.slice(0, 30),
    longDescription: common.description,
    developerName: manifest.author?.name,
    category: config.category ?? 'Developer Tools',
    capabilities: config.capabilities ?? ['Read', 'Write'],
    websiteURL: manifest.homepage,
    privacyPolicyURL: manifest.privacyPolicyUrl,
    composerIcon: icon,
    logo: icon,
  },
}));

write(join(pluginDir, '.github', 'plugin', 'plugin.json'), json({
  ...common,
  skills,
  ...(agents ? { agents: './ports/copilot/agents/' } : {}),
  ...(hooks ? { hooks: './ports/copilot/hooks.json' } : {}),
}));

// A command removed from the source leaves no skill behind.
const generated = join(pluginDir, 'ports', 'skills');

for (const folder of existsSync(generated) ? readdirSync(generated) : []) {
  const skill = join(generated, folder, 'SKILL.md');

  if (existsSync(skill) && MARKERS.some(m => readFileSync(skill, 'utf8').includes(m)) && !commands.includes(folder)) {
    remove(join(generated, folder));
  }
}

// Nor does an agent removed or renamed.
for (const folder of [join(pluginDir, 'ports', 'codex', 'agents'), join(pluginDir, 'ports', 'copilot', 'agents')]) {
  for (const file of existsSync(folder) ? readdirSync(folder) : []) {
    if (!(agents || []).includes(join(folder, file))) {
      remove(join(folder, file));
    }
  }
}

if (stale.length) {
  console.error(`${plugin}: the Codex and Copilot packages are out of date; run plugin-tools' build-ports:\n  ${stale.join('\n  ')}`);
  process.exit(1);
}

console.log(check ? `${plugin}: the Codex and Copilot packages are current.` : `${plugin}: wrote the Codex and Copilot packages.`);
